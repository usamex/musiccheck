#!/usr/bin/env python3
"""Convert a Claude Code session export (transcript.jsonl) into a readable, redacted Markdown log.

Usage:
    python3 scripts/session_to_markdown.py <transcript.jsonl> <out.md> [--title "..."]

Keeps: user messages, assistant replies, one line per tool call, subagent hand-back reports,
answers to clarifying questions. Drops: hidden reasoning, tool outputs, system/context records
(emails, local config, environment). Redacts home/temp paths and email addresses.
The raw export must never be committed — it contains personal and machine-specific data.
"""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

AGENT_NAMES = {
    "ad927b45c13278dd1": "Mobile engineer agent",
    "a2c7dc9f11b28601c": "Review agent",
}

_REDACTIONS = [
    (re.compile(r"/tmp/claude-\d+/[^\s'\"`)]*?/scratchpad"), "<scratchpad>"),
    (re.compile(r"/tmp/claude-\d+/[^\s'\"`)]*"), "<tmp>"),
    (re.compile(r"/home/[A-Za-z0-9_.-]+/"), "~/"),
    (
        re.compile(
            r"\b[A-Za-z0-9._%+-]+@(?!anthropic\.com|example\.(com|org))[A-Za-z0-9.-]+\.[a-z]{2,}\b"
        ),
        "<email>",
    ),
]
_SYSTEM_BLOCK = re.compile(r"<system-reminder>.*?</system-reminder>", re.S)
_PASTED = re.compile(r"<pasted_content[^>]*>.*?</pasted_content[^>]*>", re.S)
_AGENT_MSG = re.compile(r'<agent-message from="([^"]+)">(.*?)(?:</agent-message>|$)', re.S)


def redact(text: str) -> str:
    for pattern, repl in _REDACTIONS:
        text = pattern.sub(repl, text)
    return text


def tool_line(block: dict) -> str:
    name = block.get("name", "tool")
    inp = block.get("input") or {}
    short = name.split("__")[-1]
    detail = (
        inp.get("description")
        or inp.get("action_summary")
        or (inp.get("file_path") and f"{Path(inp['file_path']).name}")
        or inp.get("query")
        or inp.get("url")
        or inp.get("action")
        or ""
    )
    if name == "mcp__Claude_Browser__browser_batch":
        steps = [
            a.get("input", {}).get("action_summary") or a.get("name")
            for a in inp.get("actions", [])
        ]
        detail = "; ".join(s for s in steps if s)
    if name == "AskUserQuestion":
        detail = " / ".join(q.get("question", "") for q in inp.get("questions", []))
    return f"- `{short}` — {redact(str(detail))}".rstrip(" —")


def render_user_text(text: str) -> str | None:
    match = _AGENT_MSG.search(text)
    if match:
        agent = AGENT_NAMES.get(match.group(1), f"Subagent {match.group(1)[:6]}")
        body = match.group(2)
        lines = [ln[2:] if ln.startswith("  ") else ln for ln in body.splitlines()]
        # Drop the harness frame (first paragraph) and keep the report itself.
        report = "\n".join(lines)
        report = re.sub(
            r"^\s*\[Subagent hand-back\].*?The report follows:\s*", "", report, flags=re.S
        )
        return f"### Subagent report — {agent}\n\n{redact(report.strip())}"
    text = _SYSTEM_BLOCK.sub("", text)
    text = _PASTED.sub("*[Pasted project brief — saved verbatim as `PROMPT.md`]*", text)
    text = text.strip()
    return f"### User\n\n{redact(text)}" if text else None


def convert(src: Path, title: str) -> str:
    records = [json.loads(line) for line in src.read_text().splitlines() if line.strip()]
    out: list[str] = [f"# {title}", ""]
    out.append(
        "Redacted export of the Claude Code session (user messages, assistant replies, tool-call "
        "log, subagent reports). Hidden reasoning, tool outputs and environment context are "
        "omitted. Generated by `scripts/session_to_markdown.py`.\n"
    )
    pending_tools: list[str] = []
    pending_question: dict[str, str] = {}

    def flush_tools() -> None:
        if pending_tools:
            out.append(f"<details><summary>Tool calls ({len(pending_tools)})</summary>\n")
            out.extend(pending_tools)
            out.append("\n</details>\n")
            pending_tools.clear()

    for rec in records:
        kind = rec.get("type")
        msg = rec.get("message") or {}
        content = msg.get("content") if isinstance(msg, dict) else None
        if kind == "user":
            if isinstance(content, str):
                rendered = render_user_text(content)
                if rendered:
                    flush_tools()
                    stamp = rec.get("timestamp", "")[:16].replace("T", " ")
                    out.append(
                        f"{rendered}\n\n<sub>{stamp} UTC</sub>\n" if stamp else rendered + "\n"
                    )
            elif isinstance(content, list):
                for block in content:
                    if (
                        block.get("type") == "tool_result"
                        and block.get("tool_use_id") in pending_question
                    ):
                        result = block.get("content")
                        text = result if isinstance(result, str) else json.dumps(result)
                        answer = re.findall(r'"=?"([^"]+)"', text)
                        pending_tools.append(
                            f"  - answer: {redact(answer[-1] if answer else text[:300])}"
                        )
        elif kind == "assistant" and isinstance(content, list):
            for block in content:
                if block.get("type") == "text" and block.get("text", "").strip():
                    flush_tools()
                    out.append(f"### Claude\n\n{redact(block['text'].strip())}\n")
                elif block.get("type") == "tool_use":
                    pending_tools.append(tool_line(block))
                    if block.get("name") == "AskUserQuestion":
                        pending_question[block.get("id")] = "q"
    flush_tools()
    return "\n".join(out).rstrip() + "\n"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("src", type=Path)
    parser.add_argument("out", type=Path)
    parser.add_argument("--title", default="Session transcript")
    args = parser.parse_args()
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(convert(args.src, args.title))
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
